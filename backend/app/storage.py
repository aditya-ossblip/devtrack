"""Where uploaded files live.

One small interface, two places it can point:

- ``local``: a folder beside the database (``backend/instance/uploads``). For
  your own computer, Windows or macOS. Nothing to sign up for, works offline.
- ``s3``: any S3-compatible bucket: Supabase Storage on the live site today,
  or Cloudflare R2, Backblaze B2, AWS S3 later. Switching between them is a
  change of settings in ``backend/.env``, not of code.

Which one is used is ``STORAGE_BACKEND`` in the settings. The rest of the app
only ever calls ``get_storage()`` and the three methods below, so nothing
outside this file knows or cares where the bytes are.

Every file is private. The bucket is never public, and downloads always go
through the API, which checks the person is on the project first.
"""

from pathlib import Path

from flask import current_app

_EXTENSION_KEY = 'devtrack_storage'


class LocalStorage:
    """Files in a folder on this computer."""

    name = 'local'

    def __init__(self, directory):
        self.directory = Path(directory)

    def _path(self, key: str) -> Path:
        # Keys are generated by the app (random hex + extension), never taken
        # from a request; this is a second guard, not the first.
        if '/' in key or '\\' in key or '..' in key:
            raise ValueError(f'Unsafe storage key: {key!r}')
        return self.directory / key

    def save(self, key: str, data: bytes, content_type: str) -> None:
        self.directory.mkdir(parents=True, exist_ok=True)
        self._path(key).write_bytes(data)

    def read(self, key: str) -> bytes | None:
        path = self._path(key)
        return path.read_bytes() if path.exists() else None

    def delete(self, key: str) -> None:
        self._path(key).unlink(missing_ok=True)


class S3Storage:
    """Files in an S3-compatible bucket (Supabase, R2, B2, AWS...)."""

    name = 's3'

    def __init__(self, bucket: str, client, prefix: str = 'uploads/'):
        self.bucket = bucket
        self.client = client
        self.prefix = prefix

    def _key(self, key: str) -> str:
        if '/' in key or '\\' in key or '..' in key:
            raise ValueError(f'Unsafe storage key: {key!r}')
        return f'{self.prefix}{key}'

    def save(self, key: str, data: bytes, content_type: str) -> None:
        self.client.put_object(
            Bucket=self.bucket, Key=self._key(key), Body=data, ContentType=content_type,
        )

    def read(self, key: str) -> bytes | None:
        try:
            response = self.client.get_object(Bucket=self.bucket, Key=self._key(key))
        except Exception as exc:  # botocore's NoSuchKey, without importing botocore here
            code = getattr(exc, 'response', {}).get('Error', {}).get('Code', '')
            if code in ('NoSuchKey', '404', 'NotFound'):
                return None
            raise
        return response['Body'].read()

    def delete(self, key: str) -> None:
        self.client.delete_object(Bucket=self.bucket, Key=self._key(key))


def make_s3_client(config):
    """An S3 client for the settings in `config`.

    Imported here rather than at the top: boto3 is only needed when files go
    to a bucket, and a missing package must not stop the app from starting on
    a computer that stores files locally.
    """
    import boto3
    from botocore.config import Config as BotoConfig

    return boto3.client(
        's3',
        endpoint_url=config.get('S3_ENDPOINT_URL') or None,
        region_name=config.get('S3_REGION') or None,
        aws_access_key_id=config.get('S3_ACCESS_KEY_ID'),
        aws_secret_access_key=config.get('S3_SECRET_ACCESS_KEY'),
        # Path-style URLs (endpoint/bucket/key) are what Supabase and most
        # non-AWS services expect; virtual-host style needs DNS per bucket.
        config=BotoConfig(signature_version='s3v4', s3={'addressing_style': 'path'}),
    )


def build_storage(config):
    backend = (config.get('STORAGE_BACKEND') or 'local').strip().lower()
    if backend == 'local':
        return LocalStorage(config['UPLOAD_DIR'])
    if backend == 's3':
        missing = [name for name in ('S3_BUCKET', 'S3_ACCESS_KEY_ID', 'S3_SECRET_ACCESS_KEY')
                   if not config.get(name)]
        if missing:
            raise RuntimeError(f'STORAGE_BACKEND=s3 needs {", ".join(missing)} in backend/.env.')
        return S3Storage(config['S3_BUCKET'], make_s3_client(config))
    raise RuntimeError(f'Unknown STORAGE_BACKEND {backend!r}. Use "local" or "s3".')


def get_storage():
    """The storage for the running app, built once and then reused."""
    app = current_app._get_current_object()
    storage = app.extensions.get(_EXTENSION_KEY)
    if storage is None:
        storage = build_storage(app.config)
        app.extensions[_EXTENSION_KEY] = storage
    return storage


def set_storage(app, storage) -> None:
    """Swap the storage for an app (tests, scripts)."""
    app.extensions[_EXTENSION_KEY] = storage
